#!/usr/bin/env python3
"""Build the local, lossless Rahasya reading page and guide-link data."""

from __future__ import annotations

import html
import json
import shutil
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "source/pooja-rahasya-2010.json"
MAPPING = ROOT / "source/pooja-rahasya-map.json"
REFERENCE = ROOT / "site/pooja-rahasya-reference.html"
CLIENT_MAP = ROOT / "site/achar-rahasya-map.js"
PAGE_DIR = ROOT / "site/rahasya-pages"
SOURCE_PAGE_DIR = ROOT / "source/pooja-rahasya-pages"


def escape(value: object) -> str:
    return html.escape(str(value if value is not None else ""), quote=True)


def main() -> None:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    mapping = json.loads(MAPPING.read_text(encoding="utf-8"))["entries"]
    passages = source["passages"]
    by_id = {passage["id"]: passage for passage in passages}
    if len(by_id) != len(passages):
        raise ValueError("Duplicate Rahasya passage ID")
    expected_steps = {f"{n:02d}" for n in range(1, 48)}
    if set(mapping) != expected_steps:
        raise ValueError(f"Step-map mismatch: {sorted(expected_steps ^ set(mapping))}")
    for step, entry in mapping.items():
        for passage_id in entry["passageIds"]:
            if passage_id not in by_id:
                raise ValueError(f"{step} references missing passage {passage_id}")

    client = "// Generated by build/build_rahasya_reference.py\nwindow.ACHAR_RAHASYA_MAP = "
    CLIENT_MAP.write_text(client + json.dumps(mapping, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")

    step_blocks = []
    for step, entry in mapping.items():
        links = "".join(
            f'<li><a href="#passage-{escape(pid)}">{escape(by_id[pid]["title"])}'
            f' — PDF p. {escape(by_id[pid]["pdfPage"])}'
            f', printed p. {escape(by_id[pid].get("printedPage") or "not legible")}</a></li>'
            for pid in entry["passageIds"]
        )
        if not links:
            links = "<li>No direct Rahasya passage matched to this recording step.</li>"
        divergence = (
            f'<p class="divergence"><strong>Recording/book difference:</strong> {escape(entry["divergence"])}</p>'
            if entry.get("divergence") else ""
        )
        step_blocks.append(
            f'<section class="step" id="step-{step}"><h2>Recording step {step}</h2>'
            f'<p><a href="index.html#sec-{step}">Return to the 56-minute guide step</a></p>'
            f'<p class="match">Match: {escape(entry.get("matchStatus", "unreviewed"))}</p>'
            f'<ul>{links}</ul>{divergence}</section>'
        )

    used_ids = {pid for entry in mapping.values() for pid in entry["passageIds"]}
    used_pages = {int(passage["pdfPage"]) for passage in passages if passage["id"] in used_ids}
    PAGE_DIR.mkdir(parents=True, exist_ok=True)
    poppler = shutil.which("pdftoppm") or str(
        Path.home() / ".cache/codex-runtimes/codex-primary-runtime/dependencies/bin/override/pdftoppm"
    )
    pdf_file = source["source"]["file"]
    for page in sorted(used_pages):
        image = PAGE_DIR / f"page-{page:03d}.jpg"
        if image.exists():
            continue
        source_image = SOURCE_PAGE_DIR / image.name
        if source_image.exists():
            shutil.copy2(source_image, image)
            continue
        subprocess.run(
            [poppler, "-f", str(page), "-l", str(page), "-r", "160", "-jpeg",
             "-jpegopt", "quality=82", "-singlefile", pdf_file, str(image.with_suffix(""))],
            check=True,
        )
    passage_blocks = []
    for passage in passages:
        if passage["id"] not in used_ids:
            continue
        status = passage.get("transcriptionStatus", "unverified")
        status_html = (
            'Page image checked. ' + escape(status.removeprefix("page-image-verified").strip())
            if status.startswith("page-image-verified") else
            '<strong class="check">Page image reviewed; uncertain text remains.</strong> ' + escape(status.removeprefix("page-image-checked").strip())
            if status.startswith("page-image-checked") else
            '<strong class="check">Transcription requires page-image verification.</strong>'
        )
        page_note = (
            f'<p class="figure-note"><strong>Page-image detail:</strong> {escape(passage["pageImageNotes"])}</p>'
            if passage.get("pageImageNotes") else ""
        )
        printed_page = passage.get("printedPage") or "not legible in scan"
        passage_blocks.append(
            f'<article class="passage" id="passage-{escape(passage["id"])}">'
            f'<h2>{escape(passage["title"])}</h2>'
            f'<p class="meta">{escape(passage["section"])} · PDF p. {escape(passage["pdfPage"])}'
            f' · printed p. {escape(printed_page)} · {status_html}</p>'
            f'<div class="source-text">{escape(passage["text"])}</div>' +
            page_note +
            f'<details class="scan"><summary>View the original PDF page image</summary>'
            f'<a href="rahasya-pages/page-{int(passage["pdfPage"]):03d}.jpg" target="_blank">'
            f'<img loading="lazy" src="rahasya-pages/page-{int(passage["pdfPage"]):03d}.jpg" '
            f'alt="Original Pooja Rahasya PDF page {escape(passage["pdfPage"])}"></a></details>'
            '</article>'
        )

    document = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Complete matched Pooja Rahasya passages — Deva Pūjā</title>
<style>
:root{{--bg:#fbf6ee;--paper:#fffdf9;--ink:#2b2118;--accent:#9b401e;--line:#eaddc9}}
*{{box-sizing:border-box}}html{{scroll-behavior:smooth}}body{{margin:0;background:var(--bg);color:var(--ink);font:16px/1.65 system-ui,sans-serif}}
header{{background:#783114;color:#fff8ef;padding:24px 18px}}header div,main{{max-width:850px;margin:auto}}header a{{color:#ffe2c9}}h1{{font-size:1.5rem;line-height:1.25}}h2{{font-size:1.15rem;line-height:1.35}}
main{{padding:20px 16px 70px}}a{{color:var(--accent)}}.intro,.step,.passage{{background:var(--paper);border:1px solid var(--line);border-radius:12px;padding:17px 19px;margin:14px 0}}
.step:target,.passage:target{{outline:3px solid #e4b777;scroll-margin-top:10px}}.step ul{{padding-left:20px}}.step li{{margin:5px 0}}
.match,.meta{{color:#6d6255;font-size:.87rem}}.divergence{{background:#fff2dc;padding:10px 12px;border-radius:8px}}.check{{color:#8f3f24}}
.source-text{{font-family:Georgia,'Noto Serif',serif;white-space:pre-wrap;overflow-wrap:anywhere;line-height:1.65}}
.figure-note{{background:#f2f7f8;padding:10px 12px;border-radius:8px;font-size:.92rem}}
.scan{{margin-top:14px}}.scan summary{{cursor:pointer;color:var(--accent);font-weight:600}}.scan img{{display:block;width:100%;height:auto;margin-top:10px;border:1px solid var(--line)}}
.index{{display:grid;grid-template-columns:repeat(auto-fill,minmax(72px,1fr));gap:7px}}.index a{{display:block;text-align:center;padding:8px;border:1px solid var(--line);border-radius:7px;text-decoration:none}}
@media print{{header{{background:white;color:black}}.step,.passage{{break-inside:avoid}}}}
</style></head><body><header><div><a href="index.html">← Back to the guide</a><h1>Complete matched Pooja Rahasya passages</h1></div></header>
<main><section class="intro"><p>This local reference pairs matched source text with original page images for the 47-step recording guide. The page image is authoritative wherever the OCR transcription has a doubtful letter, Sanskrit word, table or diagram. PDF and printed book page numbers are both shown. The book and recording sometimes use different sequences or instructions; those differences are marked in the step index.</p>
<p>Source: <em>Devapuja Paddhati</em> (Ananda Teertha Vidyalaya, 2010), “Pooja Rahasya,” PDF pp. 71–136.</p>
<div class="index">{''.join(f'<a href="#step-{n:02d}">{n:02d}</a>' for n in range(1,48))}</div></section>
<h2>Step-to-source map</h2>{''.join(step_blocks)}
<h2>Source passages in book order</h2>{''.join(passage_blocks)}
</main></body></html>'''
    REFERENCE.write_text(document, encoding="utf-8")
    print(f"Wrote {REFERENCE} with {len(used_ids)} passages, {len(used_pages)} PDF images and 47 mapped steps")


if __name__ == "__main__":
    main()
