const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { chromium } = require('/Users/akshaytallikar/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const work = '/Users/akshaytallikar/Vedic Recitation/work/saraswati-puja';
const base = process.argv[2] || 'http://127.0.0.1:8768/';
const context = {window:{GUIDES:[]}};
vm.runInNewContext(fs.readFileSync('/tmp/vedic-saraswati-guide/site/data17.js','utf8'),context);
const guide = context.window.GUIDES[0];
(async () => {
  const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const page = await browser.newPage({viewport:{width:1200,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(new URL('site/index.html?guide=saraswati-puja',base).href);
  await page.waitForSelector('.card');
  assert.equal(await page.locator('#h-title').innerText(),'Saraswati Puja');
  assert.equal(await page.locator('#tabs .tab').count(),13);
  assert.doesNotMatch(await page.locator('#tabs').innerText(),/Sung \(67 min\)|Uttaradi Matha/);
  assert.equal(await page.locator('.card').count(),guide.sections.length);
  const lineCount=guide.sections.flatMap(s=>s.structuredBlocks.flatMap(b=>b.gloss?.lines.filter(Boolean)||[])).length;
  assert.equal(await page.locator('.chant-line').count(),lineCount);
  assert.equal(await page.locator('.lbl-c').count(),guide.sections.length);
  assert.equal(await page.locator('.lbl-a').count(),guide.sections.length);
  const checks=[];
  for (const source of guide.sources) {
    const s=guide.sections.find(s=>s.sourceId===source.id && s.structuredBlocks.some(b=>b.gloss?.lines.some(Boolean)));
    const card=page.locator('#sec-'+s.id);
    assert.match(await card.locator('.yt a').getAttribute('href'),new RegExp(source.url.split('v=')[1]));
    const block=s.structuredBlocks.find(b=>b.gloss?.lines.some(Boolean));
    const line=block.gloss.lines.find(Boolean);
    const rendered=card.locator('.chant-line').first();
    assert.ok((await rendered.innerText()).includes(line.text));
    assert.ok((await rendered.innerText()).includes(line.meaning));
    assert.equal(await rendered.locator('.gloss-token').count(),line.words.length);
    await rendered.locator('.cue-play').click();
    await page.waitForFunction(()=>document.getElementById('audio').readyState>=1 && !document.getElementById('audio').paused);
    const observed=await page.evaluate(()=>({src:document.getElementById('audio').src,time:document.getElementById('audio').currentTime,rate:document.getElementById('audio').playbackRate}));
    assert.ok(observed.src.endsWith('/site/'+s.audioFile));
    assert.ok(Math.abs(observed.time-(line.startSeconds-s.audioStartSeconds))<1.5,JSON.stringify({source:source.id,observed:observed.time,expected:line.startSeconds-s.audioStartSeconds}));
    await page.evaluate(()=>document.getElementById('audio').pause());
    checks.push({sourceId:source.id,section:s.id,clip:s.audioFile,correctSourceLink:true,lineReplay:true,observedClipTime:observed.time});
  }
  await page.locator('#search').fill('sesame');
  assert.ok(await page.locator('.card:visible').count()>0,'recipe must be searchable');
  assert.ok(await page.locator('.card:visible').count()<guide.sections.length);
  await page.locator('#search').fill('');
  const avahana=guide.sections.find(s=>s.sourceId==='avahana' && /saraswati/i.test(s.slug));
  await page.locator('#sec-'+(avahana?.id || guide.sections[0].id)).scrollIntoViewIfNeeded();
  await page.screenshot({path:work+'/preview-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile horizontal overflow');
  await page.screenshot({path:work+'/preview-mobile.png'});
  await page.goto(new URL('site/index.html?guide=achar',base).href);
  assert.equal(await page.locator('.card').count(),47);
  assert.ok(await page.locator('.chant-line').count()>100);
  await page.goto(new URL('site/index.html?guide=navaratri-nanda-deepa',base).href);
  assert.equal(await page.locator('.card').count(),50);
  await page.goto(new URL('site/index.html?guide=jyeshtha-devi-puja',base).href);
  assert.equal(await page.locator('.card').count(),33);
  assert.equal(errors.length,0,errors.join('\n'));
  const report={base,sections:guide.sections.length,lineMeanings:lineCount,contemplateActionPairs:guide.sections.length,sourcePlaybackChecks:checks,mobileOverflow:false,visibleGuides:13,archivedGuidesHidden:true,priorGuideSectionCounts:{achar:47,navaratri:50,jyeshtha:33},pageErrors:errors};
  fs.writeFileSync(work+(base.startsWith('http://127.')?'/ui-checks.json':'/live-ui-checks.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
